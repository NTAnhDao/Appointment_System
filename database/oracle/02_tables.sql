CREATE TABLE app.USERS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20) UNIQUE NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE
);

-- Người giám hộ
CREATE TABLE app.guardian (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    full_name VARCHAR2(255) NOT NULL,
    identity_number VARCHAR2(12) NOT NULL,
    phone VARCHAR2(15) NOT NULL,
    email VARCHAR2(255),

    created_at DATE DEFAULT SYSDATE
);

-- Hồ sơ bệnh nhân --
CREATE TABLE app.patient (
    id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    full_name VARCHAR2(255) NOT NULL,
    gender VARCHAR2(10) CHECK (gender IN ('male', 'female')),
    dob DATE NOT NULL,
    identity_number VARCHAR2(12) NOT NULL,
    bhyt VARCHAR2(50),

    phone VARCHAR2(15) NOT NULL,
    email VARCHAR2(255),

    province VARCHAR2(100),
    ward VARCHAR2(100),
    address_detail VARCHAR2(255),

    job VARCHAR2(100),
    ethnicity VARCHAR2(50),

    relation VARCHAR2(50),

    guardian_id NUMBER,
    user_id NUMBER NOT NULL,

    is_deleted NUMBER(1) DEFAULT 0 CHECK (is_deleted IN (0,1)),

    created_at DATE DEFAULT SYSDATE,

    -- constraints
    CONSTRAINT uq_patient_identity UNIQUE (identity_number),
    CONSTRAINT fk_patient_guardian 
        FOREIGN KEY (guardian_id) 
        REFERENCES guardian(id),

    CONSTRAINT fk_patient_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
);

CREATE INDEX idx_patient_phone ON app.patient(phone);
CREATE INDEX idx_patient_guardian ON app.patient(guardian_id);
CREATE INDEX idx_patient_user ON app.patient(user_id);

-- Chuyên khoa --
CREATE TABLE app.department (
   department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(255) NOT NULL,
   consultation_fee NUMBER(10,2) NOT NULL
);

-- Hồ sơ bác sĩ --
CREATE TABLE app.doctor (
   doctor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(255) NOT NULL,
   title VARCHAR2(50),
   department_id NUMBER NOT NULL,
   short_bio VARCHAR2(1000),
   experience_years NUMBER,
   image_url VARCHAR2(500),
   status VARCHAR2(20) DEFAULT 'ACTIVE',

   CONSTRAINT fk_doctor_department
   FOREIGN KEY (department_id) REFERENCES app.department(department_id)
);


-- Lịch làm việc của bác sĩ --
CREATE TABLE app.schedule (
   schedule_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   doctor_id NUMBER NOT NULL,

   work_date DATE NOT NULL,
   start_time TIMESTAMP NOT NULL,
   end_time TIMESTAMP NOT NULL,

   max_patients NUMBER DEFAULT 1,
   booked_count NUMBER DEFAULT 0,

   status VARCHAR2(20) DEFAULT 'AVAILABLE',

   CONSTRAINT fk_schedule_doctor
   FOREIGN KEY (doctor_id) REFERENCES app.doctor(doctor_id)

);

-- Lịch hẹn khám bệnh --
CREATE TABLE app.appointments (
    appointment_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    schedule_id NUMBER NOT NULL,
    patient_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,

    status VARCHAR2(20) DEFAULT 'pending',
    fee NUMBER(10,0),

    note VARCHAR2(1000),

    created_at DATE DEFAULT SYSDATE,
    expired_at DATE,

    CONSTRAINT fk_appointment_schedule
        FOREIGN KEY (schedule_id)
        REFERENCES app.schedule(schedule_id),

    CONSTRAINT fk_appointment_patient
        FOREIGN KEY (patient_id)
        REFERENCES app.patient(id),

    CONSTRAINT fk_appointment_user
        FOREIGN KEY (user_id)
        REFERENCES app.users(id)
);

CREATE INDEX idx_app_user ON app.appointments(user_id);

CREATE TABLE app.PAYMENTS (
    PAYMENT_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    APPOINTMENT_ID  NUMBER NOT NULL,
    AMOUNT          NUMBER(12,2) NOT NULL,
    PAYMENT_METHOD  VARCHAR2(50) NOT NULL, -- MOMO, VNPAY
    STATUS          VARCHAR2(50) NOT NULL,  -- PENDING, SUCCESS, FAILED
    ORDER_ID        VARCHAR2(100) UNIQUE NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE,
    UPDATED_AT      DATE,

    CONSTRAINT FK_PAYMENT_APPOINTMENT
    FOREIGN KEY (APPOINTMENT_ID)
    REFERENCES app.appointments(appointment_id)
);

DROP TABLE app.patient CASCADE CONSTRAINTS;
DROP TABLE app.doctor CASCADE CONSTRAINTS;
DROP TABLE app.department CASCADE CONSTRAINTS;
DROP TABLE app.schedule CASCADE CONSTRAINTS;
DROP TABLE app.appointments CASCADE CONSTRAINTS;
DROP TABLE app.PAYMENTS CASCADE CONSTRAINTS;